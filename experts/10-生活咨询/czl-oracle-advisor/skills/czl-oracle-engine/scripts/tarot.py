def _all_cards():
    cards = []
    for zh, en, kw, up, sh in MAJOR:
        cards.append({"deck": "大阿卡那", "name": zh, "en": en,
                      "keywords": kw, "upright": up, "shadow": sh})
    for suit, rows in MINOR.items():
        for name, kw, up, sh in rows:
            cards.append({"deck": "小阿卡那·" + suit, "name": name, "en": name,
                          "keywords": kw, "upright": up, "shadow": sh,
                          "suit": suit, "element": SUITS[suit]["element"],
                          "domain": SUITS[suit]["domain"]})
    return cards


DECK = _all_cards()
assert len(DECK) == 78, len(DECK)


def draw(spread="three", question=""):
    """按牌阵抽牌，不放回。"""
    if spread not in SPREADS:
        raise ValueError("未知牌阵：%s，可选 %s" % (spread, list(SPREADS)))
    title, positions = SPREADS[spread]
    rng = secrets.SystemRandom()
    picked = rng.sample(DECK, len(positions))
    out = []
    for i, card in enumerate(picked):
        reversed_ = rng.randrange(2) == 1
        out.append({
            "position": i + 1,
            "position_name": positions[i],
            "name": card["name"],
            "en": card["en"],
            "deck": card["deck"],
            "orientation": "逆位" if reversed_ else "正位",
            "keywords": card["keywords"],
            "message": card["shadow"] if reversed_ else card["upright"],
            "note": "逆位取该牌的另一面，不是简单反义" if reversed_ else "",
        })
    return {
        "system": "塔罗",
        "spread": title,
        "spread_key": spread,
        "question": question,
        "time": datetime.now(astro.CST).strftime("%Y-%m-%d %H:%M"),
        "cards": out,
        "reading_note": "塔罗反映的是提问当下你所处的位置与可用资源，不预告确定的结局。",
    }
