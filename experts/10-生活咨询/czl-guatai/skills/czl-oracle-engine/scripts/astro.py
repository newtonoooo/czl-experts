import math
from datetime import datetime, timedelta, timezone

CST = timezone(timedelta(hours=8))
J2000 = 2451545.0
DAY_SEC = 86400.0


# ---------------------------------------------------------------- 儒略日

def jd_from_datetime(dt):
    """datetime（需带时区）-> 儒略日（含小数）。采用公历儒略日数标准换算式。"""
    if dt.tzinfo is None:
        raise ValueError("jd_from_datetime 需要带时区的 datetime")
    utc = dt.astimezone(timezone.utc)
    y, m = utc.year, utc.month
    frac = (utc.hour + utc.minute / 60.0 + (utc.second + utc.microsecond / 1e6) / 3600.0) / 24.0
    a = (14 - m) // 12
    yy = y + 4800 - a
    mm = m + 12 * a - 3
    jdn = (utc.day + (153 * mm + 2) // 5 + 365 * yy
           + yy // 4 - yy // 100 + yy // 400 - 32045)
    return jdn - 0.5 + frac


def datetime_from_jd(jd, tz=CST):
    """儒略日 -> 指定时区 datetime。"""
    x = jd + 0.5
    jdn = int(math.floor(x))
    frac = x - jdn
    a = jdn + 32044
    b = (4 * a + 3) // 146097
    c = a - (146097 * b) // 4
    d = (4 * c + 3) // 1461
    e = c - (1461 * d) // 4
    mm = (5 * e + 2) // 153
    day = e - (153 * mm + 2) // 5 + 1
    month = mm + 3 - 12 * (mm // 10)
    year = 100 * b + d - 4800 + mm // 10
    micro = int(round(frac * DAY_SEC * 1e6))
    base = datetime(year, month, day, tzinfo=timezone.utc) + timedelta(microseconds=micro)
    return base.astimezone(tz)


def jd_midnight(year, month, day):
    """当地（东八区）当日 0 时的儒略日。"""
    return jd_from_datetime(datetime(year, month, day, tzinfo=CST))


# ---------------------------------------------------------------- ΔT

def delta_t(year):
    """力学时与世界时之差（秒）。1900–2150 分段多项式近似，误差 < 3 秒量级。"""
    y = year
    if y < 1900:
        t = (y - 1820) / 100.0
        return -20 + 32 * t * t
    if y < 1920:
        t = y - 1900
        return -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4
    if y < 1941:
        t = y - 1920
        return 21.20 + 0.84493 * t - 0.076100 * t ** 2 + 0.0020936 * t ** 3
    if y < 1961:
        t = y - 1950
        return 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547
    if y < 1986:
        t = y - 1975
        return 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718
    if y < 2005:
        t = y - 2000
        return (63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3
                + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5)
    if y < 2050:
        t = y - 2000
        return 62.92 + 0.32217 * t + 0.005589 * t ** 2
    if y <= 2150:
        return -20 + 32 * ((y - 1820) / 100.0) ** 2 - 0.5628 * (2150 - y)
    t = (y - 1820) / 100.0
    return -20 + 32 * t * t


def jd_tt_from_jd_ut(jd_ut):
    """世界时儒略日 -> 力学时儒略日。"""
    year = datetime_from_jd(jd_ut).year
    return jd_ut + delta_t(year) / DAY_SEC


def jd_ut_from_jd_tt(jd_tt):
    year = datetime_from_jd(jd_tt).year
    return jd_tt - delta_t(year) / DAY_SEC


# ---------------------------------------------------------------- 太阳

def _norm360(x):
    return x % 360.0


def _norm180(x):
    x = x % 360.0
    return x - 360.0 if x > 180.0 else x


def nutation_longitude(jde):
    """黄经章动 Δψ（角秒）。取主项，误差 < 0.5"。"""
    t = (jde - J2000) / 36525.0
    omega = math.radians(125.04452 - 1934.136261 * t)
    l_sun = math.radians(280.4665 + 36000.7698 * t)
    l_moon = math.radians(218.3165 + 481267.8813 * t)
    return (-17.20 * math.sin(omega) - 1.32 * math.sin(2 * l_sun)
            - 0.23 * math.sin(2 * l_moon) + 0.21 * math.sin(2 * omega))


def _vsop_sum(terms, t):
    return sum(a * math.cos(b + c * t) for a, b, c in terms)


