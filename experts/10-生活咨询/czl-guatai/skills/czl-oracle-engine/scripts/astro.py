def solve_solar_longitude(jd_guess, target_deg):
    """牛顿迭代求太阳视黄经等于 target 的力学时儒略日。"""
    jde = jd_guess
    for _ in range(12):
        lam = sun_apparent_longitude(jde)
        diff = _norm180(lam - target_deg)
        jde -= diff / 0.9856473
        if abs(diff) < 1e-7:
            break
    return jde


def solar_term_time(year, name):
    """某公历年内某节气的时刻（东八区 datetime）。"""
    target = dict(SOLAR_TERMS)[name]
    jd_jan1 = jd_midnight(year, 1, 1)
    lam0 = sun_apparent_longitude(jd_tt_from_jd_ut(jd_jan1))
    days = ((target - lam0) % 360.0) / 0.9856473
    jde = solve_solar_longitude(jd_tt_from_jd_ut(jd_jan1) + days, target)
    return datetime_from_jd(jd_ut_from_jd_tt(jde))


def solar_terms_of_year(year):
    """某公历年 24 个节气：[(名称, 东八区 datetime)]，按时间排序。"""
    out = []
    for name, _deg in SOLAR_TERMS:
        out.append((name, solar_term_time(year, name)))
    out.sort(key=lambda x: x[1])
    return out


def solar_terms_around(year):
    """覆盖 year 全年所需的节气序列：year-1 的冬至起，到 year+1 的立春止（供跨年边界判断）。"""
    items = []
    for y in (year - 1, year, year + 1):
        items.extend(solar_terms_of_year(y))
    items.sort(key=lambda x: x[1])
    return items


