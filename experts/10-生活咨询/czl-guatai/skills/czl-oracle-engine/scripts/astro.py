def earth_heliocentric_longitude(jde):
    """地球日心黄经（度，无修正）。VSOP87 以儒略千年为自变量、弧度为量纲。"""
    tau = (jde - J2000) / 365250.0
    l = (_vsop_sum(_EARTH_L0, tau)
         + _vsop_sum(_EARTH_L1, tau) * tau
         + _vsop_sum(_EARTH_L2, tau) * tau ** 2
         + _vsop_sum(_EARTH_L3, tau) * tau ** 3
         + _vsop_sum(_EARTH_L4, tau) * tau ** 4
         + _vsop_sum(_EARTH_L5, tau) * tau ** 5)
    return _norm360(math.degrees(l / 1e8))


def sun_apparent_longitude(jde):
    """太阳视黄经（度）。

    由 VSOP87 地球日心黄经推太阳地心黄经，再加 FK5 改正、章动与光行差。
    实测与紫金山天文台发布值的偏差见 TEST-REPORT（节气时刻误差 < 1 分钟）。
    """
    lam = _norm360(earth_heliocentric_longitude(jde) + 180.0)
    lam -= 0.09033 / 3600.0                    # FK5 改正
    lam += nutation_longitude(jde) / 3600.0    # 章动
    lam -= 20.4898 / 3600.0                    # 光行差（取 R≈1，误差 < 0.001"）
    return _norm360(lam)


def obliquity(jde):
    """黄赤交角（度）。"""
    t = (jde - J2000) / 36525.0
    eps = 23.43929111 - (46.8150 * t + 0.00059 * t * t - 0.001813 * t ** 3) / 3600.0
    return eps


def equation_of_time_minutes(jd_ut):
    """均时差（分钟），真太阳时 = 平太阳时 + 均时差。"""
    jde = jd_tt_from_jd_ut(jd_ut)
    t = (jde - J2000) / 36525.0
    eps = math.radians(obliquity(jde))
    lam = math.radians(sun_apparent_longitude(jde))
    alpha = math.atan2(math.cos(eps) * math.sin(lam), math.cos(lam))
    l0 = 280.46646 + 36000.76983 * t + 0.0003032 * t * t
    e = l0 - 0.0057183 - math.degrees(alpha)
    e = _norm180(e)
    return e * 4.0


