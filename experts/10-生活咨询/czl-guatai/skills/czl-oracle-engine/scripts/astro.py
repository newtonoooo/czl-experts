_SYNODIC = 29.530588861
_NEW_MOON_EPOCH = 2451550.09766  # 2000-01-06 附近的一次朔（力学时）


def _new_moon_jde(k):
    """第 k 个朔（相对 2000 年基准）的力学时儒略日，k=0 为基准。"""
    jde = _NEW_MOON_EPOCH + _SYNODIC * k
    for _ in range(10):
        elong = _norm180(moon_apparent_longitude(jde) - sun_apparent_longitude(jde))
        jde -= elong / 12.190749
        if abs(elong) < 1e-6:
            break
    return jde


def new_moons_between(jd_from, jd_to):
    """区间内的朔时刻列表（东八区 datetime，升序）。"""
    k0 = int(math.floor((jd_from - _NEW_MOON_EPOCH) / _SYNODIC)) - 2
    k1 = int(math.ceil((jd_to - _NEW_MOON_EPOCH) / _SYNODIC)) + 2
    out = []
    for k in range(k0, k1 + 1):
        jde = _new_moon_jde(k)
        jd_ut = jd_ut_from_jd_tt(jde)
        if jd_from - 2 <= jd_ut <= jd_to + 2:
            out.append(datetime_from_jd(jd_ut))
    out.sort()
    return out


def moon_phase_name(jd_ut):
    """粗略月相名（用于展示，不参与排盘）。"""
    elong = _norm360(moon_apparent_longitude(jd_tt_from_jd_ut(jd_ut))
                     - sun_apparent_longitude(jd_tt_from_jd_ut(jd_ut)))
    idx = int((elong + 22.5) // 45) % 8
    return ["朔", "蛾眉月", "上弦", "盈凸月", "望", "亏凸月", "下弦", "残月"][idx]
