def moon_apparent_longitude(jde):
    """月亮视黄经（度）。截断周期项序列，标称误差约 0.02°，朔时刻误差约 2 分钟内。"""
    t = (jde - J2000) / 36525.0
    lp = (218.3164477 + 481267.88123421 * t - 0.0015786 * t ** 2
          + t ** 3 / 538841.0 - t ** 4 / 65194000.0)
    d = (297.8501921 + 445267.1114034 * t - 0.0018819 * t ** 2
         + t ** 3 / 545868.0 - t ** 4 / 113065000.0)
    m = 357.5291092 + 35999.0502909 * t - 0.0001536 * t ** 2 + t ** 3 / 24490000.0
    mp = (134.9633964 + 477198.8675055 * t + 0.0087414 * t ** 2
          + t ** 3 / 69699.0 - t ** 4 / 14712000.0)
    f = (93.2720950 + 483202.0175233 * t - 0.0036539 * t ** 2
         - t ** 3 / 3526000.0 + t ** 4 / 863310000.0)
    e = 1 - 0.002516 * t - 0.0000074 * t * t

    s = 0.0
    for coef, cd, cm, cmp_, cf in _MOON_TERMS:
        arg = math.radians(cd * d + cm * m + cmp_ * mp + cf * f)
        k = coef
        if cm == 1 or cm == -1:
            k *= e
        elif cm == 2 or cm == -2:
            k *= e * e
        s += k * math.sin(arg)

    a1 = math.radians(119.75 + 131.849 * t)
    a2 = math.radians(53.09 + 479264.290 * t)
    s += 3958 * math.sin(a1) + 1962 * math.sin(math.radians(lp - f)) + 318 * math.sin(a2)
    return _norm360(lp + s / 1e6)


