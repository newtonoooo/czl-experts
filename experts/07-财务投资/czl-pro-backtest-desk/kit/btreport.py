"""btreport — 把回测结果渲染成一份自包含的 HTML 报告（零第三方依赖）

报告 = 一个模板文件 + 一段 JSON 载荷。模板内置在 kit/template/report.tpl.html，
用 __PAYLOAD__ / __TITLE__ / __LANG__ 三个占位符替换，不联网、不引 CDN。

对外只暴露三个函数：
    build_payload(...)   # 组装载荷，便于单独检查
    render(payload, out) # 写 HTML
    report_from_result(...)  # 一步到位：结果 → HTML
"""

from __future__ import annotations

import json
import os
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TEMPLATE = os.path.join(HERE, "template", "report.tpl.html")

DISCLAIMER = {
    "zh": "⚠️ 本页由 AI 依据历史数据计算生成，仅用于策略研究与复核，不构成任何投资建议或标的推荐。"
          "历史回测收益不代表未来表现，实盘受流动性、冲击成本与规则变化影响。",
    "en": "⚠️ Generated by AI from historical data for research and verification only. "
          "It is not investment advice or a recommendation of any security. "
          "Past backtest performance does not predict future returns.",
}


def _kpi(label, value, sub="", tone=""):
    return {"label": label, "value": value, "sub": sub, "tone": tone}


def _tone(v):
    if v is None:
        return ""
    return "up" if v > 0 else ("down" if v < 0 else "flat")


def _fmt_money(v):
    try:
        return "{:,.0f}".format(float(v))
    except Exception:
        return str(v)


def build_markers(trades, limit=200, lang="zh"):
    """成交标记：买入点为 buy，卖出点为 sell。超出上限则等距抽稀。"""
    marks = []
    for t in trades:
        if t.get("entry_date"):
            marks.append({"date": t["entry_date"], "action": "buy"})
        if t.get("exit_date"):
            marks.append({"date": t["exit_date"], "action": "sell"})
    marks.sort(key=lambda m: m["date"])
    if len(marks) > limit:
        step = len(marks) / float(limit)
        marks = [marks[int(i * step)] for i in range(limit)]
    return marks


def build_payload(result, title, subtitle="", lang="zh", benchmark=None, notes=None,
                  extra_kpis=None, markers=None, footer_extra=""):
    m = result.metrics
    meta = result.meta
    if lang == "en":
        kpis = [
            _kpi("Total return", "%+.2f%%" % m.get("total_return_pct", 0), "", _tone(m.get("total_return_pct"))),
            _kpi("Annualized", "%+.2f%%" % m.get("annual_return_pct", 0), "", _tone(m.get("annual_return_pct"))),
            _kpi("Max drawdown", "%.2f%%" % m.get("max_drawdown_pct", 0), str(m.get("max_drawdown_date", "")), "down"),
            _kpi("Sharpe", "%.2f" % m.get("sharpe", 0), "vol %.1f%%" % m.get("annual_vol_pct", 0)),
            _kpi("Win rate", "%.1f%%" % m.get("win_rate_pct", 0), "PF %.2f" % m.get("profit_factor", 0)),
            _kpi("Closed trades", str(m.get("trade_count", 0)),
                 "in market %.0f%%" % m.get("exposure_pct", 0)),
        ]
        chips = [
            {"k": "Window", "v": "%s → %s" % (meta.get("start"), meta.get("end"))},
            {"k": "Market", "v": meta.get("market", "")},
            {"k": "Universe", "v": ", ".join(meta.get("universe", []))[:48]},
            {"k": "Capital", "v": _fmt_money(meta.get("initial_cash", 0))},
            {"k": "Cost", "v": meta.get("cost_model", "")},
        ]
        default_notes = [
            {"title": "Execution", "items": [
                "Signals are evaluated on the close of bar t and filled at the open of bar t+1.",
                "End-of-sample open positions are liquidated at the final close.",
                "A-share lots of %s shares and T+1 are enforced." % meta.get("lot_size", 1),
            ]},
            {"title": "Known limits", "items": [
                "Daily bars cannot reproduce intraday stop orders; a bar's high/low order is unknown.",
                "No market-impact model: size above a few days' ADV will trade worse than modelled.",
                "Parameter choice is part of the result; see the robustness table before trusting it.",
            ]},
        ]
    else:
        kpis = [
            _kpi("累计收益", "%+.2f%%" % m.get("total_return_pct", 0), "", _tone(m.get("total_return_pct"))),
            _kpi("年化收益", "%+.2f%%" % m.get("annual_return_pct", 0), "", _tone(m.get("annual_return_pct"))),
            _kpi("最大回撤", "%.2f%%" % m.get("max_drawdown_pct", 0), "谷底 %s" % m.get("max_drawdown_date", ""), "down"),
            _kpi("夏普比率", "%.2f" % m.get("sharpe", 0), "年化波动 %.1f%%" % m.get("annual_vol_pct", 0)),
            _kpi("胜率", "%.1f%%" % m.get("win_rate_pct", 0), "盈亏比 %.2f" % m.get("profit_factor", 0)),
            _kpi("平仓笔数", str(m.get("trade_count", 0)),
                 "在场时间 %.0f%%" % m.get("exposure_pct", 0)),
        ]
        chips = [
            {"k": "区间", "v": "%s → %s" % (meta.get("start"), meta.get("end"))},
            {"k": "市场", "v": meta.get("market", "")},
            {"k": "标的", "v": ", ".join(meta.get("universe", []))[:48]},
            {"k": "初始资金", "v": _fmt_money(meta.get("initial_cash", 0))},
            {"k": "成本", "v": meta.get("cost_model", "")},
        ]
        default_notes = [
            {"title": "成交口径", "items": [
                "信号在 t 日收盘评估，t+1 日开盘成交；不存在「看到收盘价再买在收盘价」的隐含假设。",
                "样本末仍有持仓时，按最后一根 bar 收盘价强制平仓，末笔记为 eod_close。",
                "A 股按 %s 股一手、T+1 锁定；港股按每手股数；美股不设 T+1。" % meta.get("lot_size", 1),
            ]},
            {"title": "已知局限", "items": [
                "日线无法还原盘中触发顺序，止损/止盈只能近似。",
                "未建模冲击成本：单笔超过近期日均成交额一定比例时，实盘成交会更差。",
                "参数是结论的一部分，请结合稳健性扫描一起看，不要只看单一参数下的最优值。",
            ]},
        ]
    if extra_kpis:
        kpis = extra_kpis + kpis

    payload = {
        "lang": lang,
        "title": title,
        "subtitle": subtitle or ("%s｜生成于 %s" % (meta.get("strategy_name", ""),
                                                 datetime.now().strftime("%Y-%m-%d %H:%M"))),
        "chips": chips,
        "kpis": kpis,
        "equity": result.equity,
        "benchmark": benchmark or [],
        "monthly": result.monthly,
        "trades": result.trades[:400],
        "table_mode": "trades",
        "markers": markers if markers is not None else build_markers(result.trades, 200, lang),
        "notes": notes if notes is not None else default_notes,
        "warnings": result.warnings,
        "footer": DISCLAIMER.get(lang, DISCLAIMER["zh"]) + (("\n" + footer_extra) if footer_extra else ""),
    }
    return payload


def render(payload, out_path, template_path=None):
    tpl_path = template_path or DEFAULT_TEMPLATE
    with open(tpl_path, "r", encoding="utf-8") as fh:
        tpl = fh.read()
    lang = payload.get("lang", "zh")
    html = (tpl.replace("__LANG__", "zh-CN" if lang == "zh" else "en")
               .replace("__TITLE__", str(payload.get("title", "回测报告")))
               .replace("/*__PAYLOAD__*/", json.dumps(payload, ensure_ascii=False)))
    os.makedirs(os.path.dirname(os.path.abspath(out_path)) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(html)
    return out_path


def report_from_result(result, out_path="index.html", title="策略回测报告", subtitle="",
                       lang="zh", benchmark=None, notes=None, footer_extra=""):
    payload = build_payload(result, title, subtitle, lang, benchmark, notes, footer_extra=footer_extra)
    return render(payload, out_path)


def event_payload(event_rows, stats, title, lang="zh", extra=None):
    """事件研究版载荷：不使用组合层指标，只给事件层统计。"""
    if lang == "en":
        kpis = [
            _kpi("Events", str(stats.get("event_count", 0)), "skipped %s" % stats.get("skipped", 0)),
            _kpi("Average", "%+.2f%%" % stats.get("avg_pct", 0), "", _tone(stats.get("avg_pct"))),
            _kpi("Median", "%+.2f%%" % stats.get("median_pct", 0), "", _tone(stats.get("median_pct"))),
            _kpi("Win rate", "%.1f%%" % stats.get("win_rate_pct", 0)),
            _kpi("Best", "%+.2f%%" % stats.get("best_pct", 0), "", "up"),
            _kpi("Worst", "%+.2f%%" % stats.get("worst_pct", 0), "", "down"),
        ]
    else:
        kpis = [
            _kpi("事件数", str(stats.get("event_count", 0)), "跳过 %s" % stats.get("skipped", 0)),
            _kpi("平均收益", "%+.2f%%" % stats.get("avg_pct", 0), "", _tone(stats.get("avg_pct"))),
            _kpi("中位数", "%+.2f%%" % stats.get("median_pct", 0), "", _tone(stats.get("median_pct"))),
            _kpi("胜率", "%.1f%%" % stats.get("win_rate_pct", 0)),
            _kpi("最好", "%+.2f%%" % stats.get("best_pct", 0), "", "up"),
            _kpi("最差", "%+.2f%%" % stats.get("worst_pct", 0), "", "down"),
        ]
    rows = [r for r in event_rows if r.get("status") == "ok"]
    # 事件研究没有组合净值，用等权累计收益合成一条曲线供参考
    cum, curve = 1.0, []
    for r in rows:
        cum *= (1 + r["pnl_pct"] / 100.0)
        curve.append({"date": r["exit_date"], "value": round(cum * 1_000_000, 2)})
    trades = [{
        "symbol": r.get("label", ""),
        "entry_date": r.get("entry_date", ""),
        "exit_date": r.get("exit_date", ""),
        "entry_price": r.get("entry_price"),
        "exit_price": r.get("exit_price"),
        "shares": "",
        "pnl_pct": r.get("pnl_pct"),
        "holding_days": "",
    } for r in rows]
    payload = {
        "lang": lang,
        "title": title,
        "subtitle": "",
        "chips": [{"k": "事件数", "v": str(len(rows))}],
        "kpis": kpis,
        "equity": curve,
        "benchmark": [],
        "monthly": [],
        "table_mode": "event",
        "trades": trades,
        "markers": [{"date": r["entry_date"], "action": "buy"} for r in rows][:200],
        "notes": (extra or []),
        "warnings": [],
        "footer": DISCLAIMER.get(lang, DISCLAIMER["zh"]),
    }
    return payload
