/**
 * render.mjs — 渲染调度：模型 → 场景 → SVG / HTML / ASCII
 */

import { FONT_STACK, xmlEscape } from './core.mjs';
import { getTheme, DEFAULT_THEME, THEMES, cssVarBlock } from './themes.mjs';
import { sceneToSvg } from './scene.mjs';
import { paintFlow, paintClass, paintEr } from './paint-graph.mjs';
import { paintSequence } from './paint-sequence.mjs';
import { paintGantt, paintMindmap, paintTimeline, paintPie, paintQuadrant, paintXy } from './paint-data.mjs';
import { toAscii } from './ascii.mjs';
import { toMermaid } from './mermaid-export.mjs';

export function buildScene(model, theme) {
  switch (model.kind) {
    case 'flow':
    case 'state':
      return paintFlow(model, theme);
    case 'class':
      return paintClass(model, theme);
    case 'er':
      return paintEr(model, theme);
    case 'sequence':
      return paintSequence(model, theme);
    case 'gantt':
      return paintGantt(model, theme);
    case 'mindmap':
      return paintMindmap(model, theme);
    case 'timeline':
      return paintTimeline(model, theme);
    case 'pie':
      return paintPie(model, theme);
    case 'quadrant':
      return paintQuadrant(model, theme);
    case 'xy':
      return paintXy(model, theme);
    default:
      throw new Error(`不支持的图表类型: ${model.kind}`);
  }
}

export function renderSvg(model, themeName = DEFAULT_THEME, opts = {}) {
  const theme = typeof themeName === 'string' ? getTheme(themeName) : themeName;
  const scene = buildScene(model, theme);
  const svg = sceneToSvg(scene, {
    background: opts.transparent ? null : theme.bg,
    fontFamily: FONT_STACK,
    padding: opts.padding ?? 0,
    title: model.title || model.kind,
  });
  const meta = `<!-- generated by czl-diagram-forge v${opts.version || '1.0.0'} | kind=${model.kind} | theme=${theme.name} | ${new Date().toISOString()} -->`;
  return `${meta}\n${svg}`;
}

export function renderHtml(model, opts = {}) {
  const chosen = opts.theme || model.theme || DEFAULT_THEME;
  const themeList = opts.themes && opts.themes.length ? opts.themes : defaultThemeSet(chosen);
  const frames = [];
  for (const name of themeList) {
    const theme = getTheme(name);
    const scene = buildScene(model, theme);
    const svg = sceneToSvg(scene, {
      background: null,
      fontFamily: FONT_STACK,
      padding: 0,
      title: model.title || model.kind,
    });
    frames.push(`<div class="dg-frame" data-theme="${name}" data-mode="${theme.mode}">${svg}</div>`);
  }
  const title = model.title || '图表预览';
  const buttons = themeList
    .map(
      (n) =>
        `<button type="button" class="dg-theme-btn${n === chosen ? ' is-active' : ''}" data-target="${n}" title="${THEMES[n].label}">${THEMES[n].label}</button>`,
    )
    .join('');

  const vars = themeList
    .map((n) => cssVarBlock(THEMES[n], `.dg-body[data-theme="${n}"]`))
    .join('\n');

  return `<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>${xmlEscape(title)}</title>
<style>
${vars}
*{box-sizing:border-box}
html,body{margin:0;height:100%}
body{font-family:${FONT_STACK};background:var(--dg-bg);color:var(--dg-fg);transition:background .18s ease}
.dg-bar{position:sticky;top:0;z-index:9;display:flex;gap:10px;align-items:center;flex-wrap:wrap;
  padding:10px 16px;background:color-mix(in srgb,var(--dg-bg) 86%,transparent);backdrop-filter:blur(8px);
  border-bottom:1px solid var(--dg-border)}
.dg-bar h1{font-size:14px;font-weight:650;margin:0 12px 0 0;letter-spacing:.2px}
.dg-bar .sp{flex:1}
.dg-btn,.dg-theme-btn{font:inherit;font-size:12px;line-height:1;padding:7px 11px;border-radius:7px;cursor:pointer;
  border:1px solid var(--dg-border);background:var(--dg-surface);color:var(--dg-fg)}
.dg-btn:hover,.dg-theme-btn:hover{border-color:var(--dg-accent)}
.dg-theme-btn.is-active{border-color:var(--dg-accent);background:color-mix(in srgb,var(--dg-accent) 14%,var(--dg-surface));font-weight:600}
.dg-stage{position:relative;overflow:auto;height:calc(100% - 53px);padding:24px}
.dg-canvas{transform-origin:0 0;transition:transform .12s ease;width:max-content}
.dg-frame{display:none}
.dg-frame.is-active{display:block}
.dg-frame svg{display:block;max-width:none;height:auto}
.dg-hint{position:fixed;right:14px;bottom:12px;font-size:11px;color:var(--dg-muted);opacity:.8}
</style>
</head>
<body class="dg-body" data-theme="${chosen}">
<div class="dg-bar">
  <h1>${xmlEscape(title)}</h1>
  <span class="sp"></span>
  ${buttons}
  <span class="sp"></span>
  <button class="dg-btn" data-act="out" title="缩小">−</button>
  <button class="dg-btn" data-act="in" title="放大">+</button>
  <button class="dg-btn" data-act="reset" title="复位">100%</button>
</div>
<div class="dg-stage" id="stage">
  <div class="dg-canvas" id="canvas">
    ${frames.join('\n')}
  </div>
</div>
<div class="dg-hint">滚轮缩放 · 拖拽平移</div>
<script>
(function(){
  var body=document.body, canvas=document.getElementById('canvas'), stage=document.getElementById('stage');
  var scale=1, tx=0, ty=0, dragging=false, sx=0, sy=0;
  function apply(){canvas.style.transform='translate('+tx+'px,'+ty+'px) scale('+scale+')';}
  function setTheme(name){
    body.dataset.theme=name;
    document.querySelectorAll('.dg-frame').forEach(function(f){f.classList.toggle('is-active', f.dataset.theme===name);});
    document.querySelectorAll('.dg-theme-btn').forEach(function(b){b.classList.toggle('is-active', b.dataset.target===name);});
  }
  document.querySelectorAll('.dg-theme-btn').forEach(function(b){b.addEventListener('click',function(){setTheme(b.dataset.target);});});
  document.querySelectorAll('[data-act]').forEach(function(b){b.addEventListener('click',function(){
    var a=b.dataset.act;
    if(a==='in') scale=Math.min(4,scale*1.15);
    if(a==='out') scale=Math.max(0.2,scale/1.15);
    if(a==='reset'){scale=1;tx=0;ty=0;}
    apply();
  });});
  stage.addEventListener('wheel',function(e){
    if(!e.ctrlKey && !e.metaKey) return;
    e.preventDefault();
    var r=stage.getBoundingClientRect(), mx=e.clientX-r.left, my=e.clientY-r.top;
    var next=Math.min(4,Math.max(0.2,scale*(e.deltaY<0?1.08:0.925)));
    tx=mx-(mx-tx)*(next/scale); ty=my-(my-ty)*(next/scale); scale=next; apply();
  },{passive:false});
  stage.addEventListener('mousedown',function(e){dragging=true;sx=e.clientX-tx;sy=e.clientY-ty;stage.style.cursor='grabbing';});
  window.addEventListener('mousemove',function(e){if(!dragging)return;tx=e.clientX-sx;ty=e.clientY-sy;apply();});
  window.addEventListener('mouseup',function(){dragging=false;stage.style.cursor='';});
  setTheme('${chosen}');
})();
</script>
</body>
</html>`;
}

function defaultThemeSet(chosen) {
  const set = [chosen];
  for (const alt of ['graphite', 'midnight', 'nordic', 'paper', 'plum', 'ocean']) {
    if (set.length >= 4) break;
    if (!set.includes(alt) && THEMES[alt]) set.push(alt);
  }
  return set;
}

export function renderAscii(model) {
  return toAscii(model);
}

export { toMermaid };
